"""
Evolving prey: orientation challenge ("DVD logo" mode).

A road is drawn on screen and everything outside it is red and kills.
Balls bounce off the window edges like the DVD logo, and the only gene is
the launch angle. Generation after generation, the balls learn the exact
angle that keeps them on the road through every bounce, all the way to the finish.

The road is generated by launching a reference ball with a *secret angle*,
so a perfect solution always exists, and we can measure how close the
evolution gets to it. Roads whose parts pass close to each other are
rejected, so the road never crosses itself.

    python orientation.py --view                         # live Tkinter view
    python orientation.py --generations 30 --gif         # headless: plots + GIFs
"""
import argparse
import math
import os
import random

import numpy as np
from PIL import Image, ImageDraw

from simulation import MovingCircle, weighted_circular_mean_std, WIDTH, HEIGHT

SPEED = 4            # px / frame, fixed
DIAMETER = 10        # fixed
ROAD_WIDTH = 36
FITNESS_EXPONENT = 5
MIN_ANGLE_MUTATION = 0.02   # degrees

ROAD_RGB, KILL_RGB, BALL_RGB = (48, 54, 61), (120, 22, 28), (59, 130, 246)


# --------------------------------------------------------------------------
# Track
# --------------------------------------------------------------------------
def _segment_distance(p1, p2, q1, q2):
    def point_seg(p, a, b):
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = dx * dx + dy * dy
        t = 0 if L == 0 else max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L))
        return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)

    def orient(p, q, r):
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])

    if orient(p1, p2, q1) * orient(p1, p2, q2) < 0 and orient(q1, q2, p1) * orient(q1, q2, p2) < 0:
        return 0.0   # the segments cross
    return min(point_seg(p1, q1, q2), point_seg(p2, q1, q2), point_seg(q1, p1, p2), point_seg(q2, p1, p2))


class Track:
    """Road following the bouncing trajectory of a ball launched at a secret angle."""

    def __init__(self, bounces=6, width=ROAD_WIDTH, max_tries=50000):
        self.width = width
        for _ in range(max_tries):
            if self._try(bounces):
                break
        else:
            raise RuntimeError("no clean track found, try fewer bounces")

        # Mask of positions where a ball *center* is safe (road minus ball radius)
        img = Image.new("1", (WIDTH, HEIGHT), 0)
        d = ImageDraw.Draw(img)
        safe = width - DIAMETER
        d.line(self.vertices, fill=1, width=safe, joint="curve")
        for (x, y) in (self.vertices[0], self.vertices[-1]):
            d.ellipse([x - safe / 2, y - safe / 2, x + safe / 2, y + safe / 2], fill=1)
        self.safe = np.array(img, dtype=bool)

    def _try(self, bounces):
        start = (random.uniform(60, WIDTH - 60), random.uniform(60, HEIGHT - 60))
        angle = random.uniform(15, 75) + 90 * random.randint(0, 3)   # never nearly flat
        a = math.radians(angle)
        ref = MovingCircle(*start, DIAMETER, SPEED * math.cos(a), SPEED * math.sin(a))
        vertices, n, frames = [start], 0, 0

        def step():
            dx, dy = ref.dx, ref.dy
            ref.move()
            return (dx > 0) != (ref.dx > 0) or (dy > 0) != (ref.dy > 0)   # bounced?

        while n < bounces:
            frames += 1
            if step():
                n += 1
                vertices.append((ref.x, ref.y))
        for _ in range(60):            # final straight line to the finish
            frames += 1
            if step():
                return False
        vertices.append((ref.x, ref.y))

        segs = list(zip(vertices[:-1], vertices[1:]))
        if min(math.dist(*s) for s in segs) < 80:           # no tiny corner bounces
            return False
        for i in range(len(segs)):                           # road never touches itself
            for j in range(i + 2, len(segs)):
                if _segment_distance(*segs[i], *segs[j]) < 1.5 * self.width:
                    return False
        self.start, self.secret_angle = start, angle % 360
        self.vertices, self.finish, self.frames = vertices, vertices[-1], frames
        return True

    def on_road(self, x, y):
        xi, yi = int(round(x)), int(round(y))
        return 0 <= xi < WIDTH and 0 <= yi < HEIGHT and self.safe[yi, xi]


# --------------------------------------------------------------------------
# World: one generation
# --------------------------------------------------------------------------
class Ball(MovingCircle):
    def __init__(self, angle, start):
        a = math.radians(angle)
        super().__init__(*start, DIAMETER, SPEED * math.cos(a), SPEED * math.sin(a), genome=angle)
        self.trail = [start]


class OrientationWorld:
    def __init__(self, angles, track):
        self.track = track
        self.frame = 0
        self.prey = [Ball(a, track.start) for a in angles]

    @property
    def alive(self):
        return [p for p in self.prey if p.alive]

    @property
    def done(self):
        return self.frame >= self.track.frames or not self.alive

    def step(self):
        self.frame += 1
        for p in self.alive:
            p.move()
            p.trail.append((p.x, p.y))
            if not self.track.on_road(p.x, p.y):
                p.alive, p.time = False, self.frame
        if self.done:
            for p in self.alive:   # reached the finish
                p.time = self.frame

    def run(self):
        while not self.done:
            self.step()
        return self.prey


# --------------------------------------------------------------------------
# Evolution (same recipe as the size / speed version)
# --------------------------------------------------------------------------
def random_angles(n):
    return [random.uniform(0, 360) for _ in range(n)]


def next_generation(prey, gen, n):
    """
    Same recipe as the predators challenge:
    parent angle = mean of the angles weighted by survival_time ** 5, computed as a
    circular mean (359 and 1 degrees are neighbours, so we average unit vectors);
    mutation = exponential noise with a random sign whose scale is the weighted spread
    of the angles, so the search tightens as soon as the best balls agree.
    """
    tmax = max(p.time for p in prey) or 1
    w = [(p.time / tmax) ** FITNESS_EXPONENT for p in prey]
    parent, spread = weighted_circular_mean_std([p.genome for p in prey], w)
    spread = max(spread, MIN_ANGLE_MUTATION)
    return [(parent + random.expovariate(1 / spread) * random.choice([-1, 1])) % 360
            for _ in range(n)]


def angle_error(a, b):
    return abs((a - b + 180) % 360 - 180)


def stats(prey, gen, track):
    return {
        "generation": gen,
        "mean_time": sum(p.time for p in prey) / len(prey),
        "best_time": max(p.time for p in prey),
        "finishers": sum(p.alive for p in prey),
        "mean_angle_error": sum(angle_error(p.genome, track.secret_angle) for p in prey) / len(prey),
    }


# --------------------------------------------------------------------------
# Rendering (PIL) for plots / GIFs
# --------------------------------------------------------------------------
def draw_track(track, scale=1.0):
    img = Image.new("RGB", (int(WIDTH * scale), int(HEIGHT * scale)), KILL_RGB)
    d = ImageDraw.Draw(img)
    pts = [(x * scale, y * scale) for x, y in track.vertices]
    d.line(pts, fill=ROAD_RGB, width=int(track.width * scale), joint="curve")
    r = track.width * scale / 2
    for (x, y) in (pts[0], pts[-1]):
        d.ellipse([x - r, y - r, x + r, y + r], fill=ROAD_RGB)
    fx, fy = pts[-1]
    d.rectangle([fx - 7 * scale, fy - 7 * scale, fx + 7 * scale, fy + 7 * scale], fill=(245, 197, 66))
    return img


def draw_scene(track, prey, text="", trails=True, balls=True):
    img = draw_track(track)
    d = ImageDraw.Draw(img)
    if trails:
        for p in prey:
            if len(p.trail) > 1:
                d.line(p.trail, fill=(110, 160, 255) if p.alive else (160, 160, 190), width=1)
    if balls:
        for p in prey:
            if p.alive:
                r = p.diameter / 2
                d.ellipse([p.x - r, p.y - r, p.x + r, p.y + r], fill=BALL_RGB)
    if text:
        d.text((12, 10), text, fill="white", font_size=24)
    return img


def render_run_gif(angles, track, path, label, every=4):
    """GIF of one generation running."""
    world = OrientationWorld(angles, track)
    frames = []
    while not world.done:
        world.step()
        if world.frame % every == 0 or world.done:
            img = draw_scene(track, world.prey, f"{label}   alive {len(world.alive)}/{len(angles)}",
                             trails=False)
            frames.append(img.resize((WIDTH // 2, HEIGHT // 2), Image.LANCZOS))
    frames += [frames[-1]] * 20
    frames[0].save(path, save_all=True, append_images=frames[1:], duration=40, loop=0)


def render_timelapse_gif(history, track, path):
    """One frame per generation with every trajectory: you see the fan of paths converge."""
    frames = []
    for gen, prey in history:
        n = len(prey)
        img = draw_scene(track, prey, f"generation {gen}   finish {sum(p.alive for p in prey)}/{n}",
                         balls=False)
        frames.append(img.resize((WIDTH // 2, HEIGHT // 2), Image.LANCZOS))
    durations = [500] * len(frames)
    durations[-1] = 2500
    frames[0].save(path, save_all=True, append_images=frames[1:], duration=durations, loop=0)


def plot(rows, path, track):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    g = [r["generation"] for r in rows]
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.6))
    ax[0].plot(g, [r["mean_time"] for r in rows], label="mean", color="tab:blue")
    ax[0].plot(g, [r["best_time"] for r in rows], label="best", color="tab:blue", alpha=.35)
    ax[0].axhline(track.frames, color="goldenrod", ls="--", label="finish")
    ax[0].set_title("Survival time (frames)"); ax[0].legend()
    ax[1].plot(g, [r["finishers"] for r in rows], color="tab:green")
    ax[1].set_title("Balls reaching the finish")
    ax[2].semilogy(g, [max(r["mean_angle_error"], 1e-3) for r in rows], color="tab:purple")
    ax[2].set_title("Mean error vs secret angle (deg, log)")
    for a in ax:
        a.set_xlabel("generation"); a.grid(alpha=.3)
    fig.tight_layout(); fig.savefig(path, dpi=120); plt.close(fig)


# --------------------------------------------------------------------------
# Tkinter live view
# --------------------------------------------------------------------------
def view(args, track):
    import tkinter as tk
    import gui
    from gui import BG, PANEL, FG, MUTED, BLUE, GREEN, ORANGE

    PANEL_W = 280
    root = tk.Tk()
    root.title("Evolving prey | orientation (DVD mode)")
    root.resizable(False, False)
    root.configure(bg=BG)
    canvas = tk.Canvas(root, width=WIDTH, height=HEIGHT, bg="#%02x%02x%02x" % KILL_RGB, highlightthickness=0)
    canvas.grid(row=0, column=0)
    panel = tk.Canvas(root, width=PANEL_W, height=HEIGHT, bg=PANEL, highlightthickness=0)
    panel.grid(row=0, column=1)

    road = "#%02x%02x%02x" % ROAD_RGB
    flat = [c for v in track.vertices for c in v]
    canvas.create_line(*flat, width=track.width, fill=road, capstyle="round", joinstyle="round")
    fx, fy = track.finish
    canvas.create_rectangle(fx - 7, fy - 7, fx + 7, fy + 7, fill=gui.GOLD, outline="")
    sx, sy = track.start
    canvas.create_text(sx, sy - 26, text="START", fill=FG, font=gui.FONT_SMALL)
    canvas.create_text(fx, fy - 22, text="FINISH", fill=gui.GOLD, font=gui.FONT_SMALL)
    hud = canvas.create_text(10, 10, anchor="nw", fill=FG, font=gui.FONT, text="")

    panel.create_text(16, 16, anchor="nw", text="DVD mode", fill=FG, font=gui.FONT_BIG)
    panel.create_text(16, 46, anchor="nw", width=PANEL_W - 30, fill=MUTED, font=gui.FONT_SMALL,
                      text=f"Gene: launch angle  |  population {args.population}\n"
                           f"Stay on the road for {len(track.vertices) - 2} bounces")
    w = PANEL_W - 32
    charts = {
        "time": gui.MiniChart(panel, 16, 92, w, 92, "Survival time (frames)  mean / best", BLUE,
                              fmt="{:.0f}", ref=track.frames),
        "fin": gui.MiniChart(panel, 16, 200, w, 92, f"Balls at the finish (/{args.population})", GREEN,
                             fmt="{:.0f}"),
        "err": gui.MiniChart(panel, 16, 308, w, 92, "Mean angle error (deg, log)", ORANGE,
                             log=True, fmt="{:.2f}"),
    }
    status = panel.create_text(16, 418, anchor="nw", fill=FG, font=gui.FONT, text="")
    panel.create_text(16, HEIGHT - 16, anchor="sw", fill=MUTED, font=gui.FONT_SMALL,
                      text="Space  next generation\nA  auto mode\nF  fast mode\nR  restart\nQ  quit")

    st = {"gen": 0, "angles": random_angles(args.population), "auto": args.auto, "fast": False,
          "paused": False, "history": [], "job": None}

    def update_status():
        on = lambda b: "ON" if b else "off"
        panel.itemconfig(status, text=f"Generation {st['gen']}\nAuto: {on(st['auto'])}    "
                                      f"Fast: {on(st['fast'])}")

    def start_generation():
        st["paused"] = False
        canvas.delete("ball", "trail", "overlay")
        st["world"] = world = OrientationWorld(st["angles"], track)
        st["items"] = {p: canvas.create_oval(0, 0, 0, 0, fill=BLUE, outline="", tags="ball") for p in world.prey}
        update_status()
        loop()

    def loop():
        world = st["world"]
        for _ in range(8 if st["fast"] else 1):
            world.step()
            if world.frame % 3 == 0 or world.done:   # draw trails every 3 frames
                for p in world.prey:
                    if p.alive or p.time == world.frame:
                        (x0, y0), (x1, y1) = p.trail[max(0, len(p.trail) - 4)], p.trail[-1]
                        canvas.create_line(x0, y0, x1, y1, fill="#6b8fc9", tags="trail")
            if world.done:
                break
        canvas.tag_raise("ball")
        for p, item in st["items"].items():
            if p.alive:
                r = p.diameter / 2
                canvas.coords(item, p.x - r, p.y - r, p.x + r, p.y + r)
            else:
                canvas.itemconfig(item, state="hidden")
        canvas.itemconfig(hud, text=f"Generation {st['gen']}    alive {len(world.alive)}/{args.population}"
                                    f"    frame {world.frame}/{track.frames}")
        if world.done:
            end_generation()
        else:
            st["job"] = root.after(5, loop)

    def end_generation():
        st["job"] = None
        st["paused"] = True
        s = stats(st["world"].prey, st["gen"], track)
        h = st["history"]
        h.append(s)
        charts["time"].update([r["mean_time"] for r in h], [r["best_time"] for r in h])
        charts["fin"].update([r["finishers"] for r in h])
        charts["err"].update([r["mean_angle_error"] for r in h])
        gui.overlay(canvas, WIDTH / 2, HEIGHT / 2, f"Generation {st['gen']}",
                    [f"Reached the finish: {s['finishers']}/{args.population}",
                     f"Mean survival: {s['mean_time']:.0f} / {track.frames} frames",
                     f"Mean angle error: {s['mean_angle_error']:.2f} deg"],
                    "Space: next generation")
        if st["auto"]:
            st["job"] = root.after(600, next_gen)

    def next_gen():
        if not st["paused"]:
            return
        st["gen"] += 1
        st["angles"] = next_generation(st["world"].prey, st["gen"], args.population)
        start_generation()

    def toggle(name):
        st[name] = not st[name]
        update_status()
        if name == "auto" and st["auto"] and st["paused"]:
            next_gen()

    def restart():
        if st["job"]:
            root.after_cancel(st["job"])
        st.update(gen=0, angles=random_angles(args.population), history=[])
        for ch in charts.values():
            ch.update([])
        start_generation()

    gui.bind_keys(root, {"space": next_gen, "a": lambda: toggle("auto"), "f": lambda: toggle("fast"),
                         "r": restart, "q": root.destroy, "escape": root.destroy})
    start_generation()
    root.mainloop()


# --------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description="Orientation challenge (DVD mode)")
    ap.add_argument("--view", action="store_true", help="live Tkinter view")
    ap.add_argument("--auto", action="store_true", help="(view) start in auto mode")
    ap.add_argument("--generations", type=int, default=30)
    ap.add_argument("--population", type=int, default=30)
    ap.add_argument("--bounces", type=int, default=6, help="number of bounces on the road (3 to 8)")
    ap.add_argument("--seed", type=int, default=None, help="same seed = same road")
    ap.add_argument("--gif", action="store_true")
    ap.add_argument("--out", default="results")
    args = ap.parse_args()

    if args.seed is not None:
        random.seed(args.seed)
    track = Track(bounces=args.bounces)
    if args.view:
        return view(args, track)

    os.makedirs(args.out, exist_ok=True)
    angles = random_angles(args.population)
    rows, history = [], []
    for gen in range(args.generations):
        prey = OrientationWorld(angles, track).run()
        history.append((gen, prey))
        rows.append(stats(prey, gen, track))
        r = rows[-1]
        print(f"gen {gen:3d} | survival {r['mean_time']:6.1f}/{track.frames} | finish {r['finishers']:2d}"
              f"/{args.population} | mean angle error {r['mean_angle_error']:8.3f} deg")
        angles = next_generation(prey, gen + 1, args.population)

    print(f"secret angle: {track.secret_angle:.3f} deg")
    plot(rows, os.path.join(args.out, "orientation.png"), track)
    draw_scene(track, history[0][1], "generation 0").save(os.path.join(args.out, "orientation_gen0.png"))
    draw_scene(track, history[-1][1], f"generation {args.generations - 1}").save(
        os.path.join(args.out, "orientation_last.png"))
    print(f"saved {args.out}/orientation.png and trajectory images")
    if args.gif:
        render_timelapse_gif(history, track, os.path.join(args.out, "orientation_timelapse.gif"))
        render_run_gif([p.genome for p in history[-1][1]], track,
                       os.path.join(args.out, "orientation_last.gif"), f"generation {args.generations - 1}")
        print("saved orientation_timelapse.gif and orientation_last.gif")


if __name__ == "__main__":
    main()
